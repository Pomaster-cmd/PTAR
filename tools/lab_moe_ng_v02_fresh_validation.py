"""LAB16: post-freeze fresh validation of the frozen LAB15 outer-balance router.

This is a validation protocol, not a tuning sweep. The LAB15 candidate was
frozen before this generator was authored. Every HR reference in this script
is newly generated by deterministic analytic/procedural definitions. LR input
uses the exact PTAR-PERCEPTUAL-V1-A downsample contract:
  skimage.transform.resize, order=3, mode='reflect', anti_aliasing=True,
  preserve_range=True, clip=True, sRGB/code-value domain.

After the first observed LAB16 result, neither candidate parameters nor gates
in this file may be changed to improve LAB16. A failed gate rejects this frozen
candidate; a later candidate requires another fresh validation set.
"""
